const dict = { it, en, es, fr, de };
let current = "it";

export const getLang = () => current;
export const has = (key) => key in dict[current] || key in it;

export function setLang(lang) {
  current = lang in dict ? lang : "it";
  document.documentElement.lang = current;
}

// Lingua iniziale: quella salvata, altrimenti quella del telefono (se supportata), altrimenti italiano.
export function detectLang(saved) {
  if (saved && saved in dict) return saved;
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = String(l).slice(0, 2).toLowerCase();
    if (code in dict) return code;
  }
  return "it";
}

export function t(key, params) {
  const text = dict[current][key] ?? it[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? "")) : text;
}

export const plural = (key, n, params) => t(`${key}.${n === 1 ? "one" : "other"}`, { n, ...params });

// Traduce i testi fissi della pagina (attributi data-i18n*).
export function applyStatic(root = document) {
  document.title = t("meta.title");
  document.querySelector('meta[name="description"]')?.setAttribute("content", t("meta.description"));
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria-label]")) el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel));
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  document.getElementById("lang-select")?.setAttribute("aria-label", t("home.language"));
}
